-- Dreaming Rose: reportes de juegos. Límite estricto de 3 reportes diarios por usuario.
CREATE TABLE IF NOT EXISTS public.reportes_juegos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  juego_id bigint NOT NULL REFERENCES public.juegos(id) ON DELETE CASCADE,
  reportante_id uuid NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  motivo text NOT NULL CHECK (motivo IN ('contenido_inapropiado','enlace_roto','archivo_sospechoso','descripcion_engañosa','spam','derechos_autor','otro')),
  detalle text NOT NULL CHECK (char_length(trim(detalle)) BETWEEN 10 AND 1200),
  estado text NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','en_revision','resuelto','descartado')),
  revisado_por uuid REFERENCES public.usuarios(id) ON DELETE SET NULL,
  revisado_at timestamptz,
  resolucion text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT reportes_juegos_no_duplicate_pending UNIQUE (juego_id, reportante_id, estado)
);
-- Unique anterior incluye estados históricos; se reemplaza por índice parcial para permitir nuevos reportes tras resolución.
ALTER TABLE public.reportes_juegos DROP CONSTRAINT IF EXISTS reportes_juegos_no_duplicate_pending;
CREATE UNIQUE INDEX IF NOT EXISTS reportes_juegos_pending_unique_idx ON public.reportes_juegos(juego_id, reportante_id) WHERE estado IN ('pendiente','en_revision');
CREATE INDEX IF NOT EXISTS reportes_juegos_estado_created_idx ON public.reportes_juegos(estado, created_at DESC);
CREATE INDEX IF NOT EXISTS reportes_juegos_reportante_created_idx ON public.reportes_juegos(reportante_id, created_at DESC);
ALTER TABLE public.reportes_juegos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.reportes_juegos FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.reportes_juegos TO authenticated;
DROP POLICY IF EXISTS reportes_juegos_select_own_or_staff ON public.reportes_juegos;
CREATE POLICY reportes_juegos_select_own_or_staff ON public.reportes_juegos FOR SELECT TO authenticated
USING (reportante_id = (SELECT auth.uid()) OR (SELECT private.mi_rol()) IN ('moderador','root'));

CREATE OR REPLACE FUNCTION public.enviar_reporte_juego(p_juego_id bigint, p_motivo text, p_detalle text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $function$
DECLARE v_uid uuid := auth.uid(); v_role text; v_owner uuid; v_count integer; v_id bigint; v_today_start timestamptz; v_today_end timestamptz;
BEGIN
 IF v_uid IS NULL THEN RAISE EXCEPTION 'Iniciá sesión para reportar un juego.'; END IF;
 v_role := private.mi_rol();
 IF v_role = 'banned' THEN RAISE EXCEPTION 'Tu cuenta no puede enviar reportes.'; END IF;
 IF p_motivo NOT IN ('contenido_inapropiado','enlace_roto','archivo_sospechoso','descripcion_engañosa','spam','derechos_autor','otro') THEN RAISE EXCEPTION 'Seleccioná un motivo válido.'; END IF;
 IF char_length(trim(coalesce(p_detalle,''))) < 10 OR char_length(trim(coalesce(p_detalle,''))) > 1200 THEN RAISE EXCEPTION 'La explicación debe tener entre 10 y 1200 caracteres.'; END IF;
 SELECT j.user_id INTO v_owner FROM public.juegos j WHERE j.id=p_juego_id AND j.estado_moderacion='aprobado';
 IF NOT FOUND THEN RAISE EXCEPTION 'El juego no existe o no está publicado.'; END IF;
 IF v_owner = v_uid THEN RAISE EXCEPTION 'No podés reportar una publicación propia.'; END IF;
 -- Serializa los envíos de cada usuario para que el límite no pueda superarse con solicitudes simultáneas.
 PERFORM pg_advisory_xact_lock(hashtextextended(v_uid::text, 0));
 v_today_start := date_trunc('day', now() AT TIME ZONE 'America/Argentina/Buenos_Aires') AT TIME ZONE 'America/Argentina/Buenos_Aires';
 v_today_end := v_today_start + interval '1 day';
 SELECT count(*) INTO v_count FROM public.reportes_juegos r WHERE r.reportante_id=v_uid AND r.created_at>=v_today_start AND r.created_at<v_today_end;
 IF v_count >= 3 THEN RAISE EXCEPTION 'Alcanzaste el máximo de 3 reportes por día. Podés volver a reportar mañana.'; END IF;
 IF EXISTS (SELECT 1 FROM public.reportes_juegos r WHERE r.juego_id=p_juego_id AND r.reportante_id=v_uid AND r.estado IN ('pendiente','en_revision')) THEN RAISE EXCEPTION 'Ya tenés un reporte pendiente para este juego.'; END IF;
 INSERT INTO public.reportes_juegos(juego_id,reportante_id,motivo,detalle) VALUES(p_juego_id,v_uid,p_motivo,trim(p_detalle)) RETURNING id INTO v_id;
 RETURN jsonb_build_object('ok',true,'id',v_id,'remaining_today',2-v_count);
END;
$function$;
REVOKE ALL ON FUNCTION public.enviar_reporte_juego(bigint,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.enviar_reporte_juego(bigint,text,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_resolver_reporte_juego(p_reporte_id bigint,p_estado text,p_resolucion text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $function$
DECLARE v_uid uuid := auth.uid(); v_role text; v_report public.reportes_juegos%ROWTYPE; v_title text; v_username text;
BEGIN
 IF v_uid IS NULL THEN RAISE EXCEPTION 'Iniciá sesión.'; END IF;
 v_role := private.mi_rol();
 IF v_role NOT IN ('moderador','root') THEN RAISE EXCEPTION 'No tenés permisos para resolver reportes.'; END IF;
 IF p_estado NOT IN ('en_revision','resuelto','descartado') THEN RAISE EXCEPTION 'Estado de resolución no válido.'; END IF;
 IF char_length(trim(coalesce(p_resolucion,''))) < 5 OR char_length(trim(coalesce(p_resolucion,''))) > 1000 THEN RAISE EXCEPTION 'Indicá una resolución de entre 5 y 1000 caracteres.'; END IF;
 SELECT * INTO v_report FROM public.reportes_juegos WHERE id=p_reporte_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'No se encontró el reporte.'; END IF;
 SELECT title INTO v_title FROM public.juegos WHERE id=v_report.juego_id;
 SELECT username INTO v_username FROM public.usuarios WHERE id=v_report.reportante_id;
 UPDATE public.reportes_juegos SET estado=p_estado,revisado_por=v_uid,revisado_at=now(),resolucion=trim(p_resolucion) WHERE id=p_reporte_id;
 INSERT INTO public.admin_audit_log(actor_id,actor_role,action_key,target_type,target_id,target_label,reason,before_data,after_data)
 VALUES(v_uid,v_role,'report.resolved','reporte',p_reporte_id::text,coalesce(v_title,'Juego eliminado'),trim(p_resolucion),jsonb_build_object('estado',v_report.estado),jsonb_build_object('estado',p_estado,'juego_id',v_report.juego_id,'reportante',v_username));
 RETURN jsonb_build_object('ok',true,'id',p_reporte_id,'estado',p_estado);
END;
$function$;
REVOKE ALL ON FUNCTION public.admin_resolver_reporte_juego(bigint,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_resolver_reporte_juego(bigint,text,text) TO authenticated;

