CREATE TABLE IF NOT EXISTS public.admin_audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id uuid REFERENCES public.usuarios(id) ON DELETE SET NULL,
    actor_username text,
    actor_role text NOT NULL,
    action_key text NOT NULL CHECK (action_key IN (
        'user.role_changed', 'game.moderation_changed', 'game.deleted',
        'creator_request.resolved', 'appeal.resolved'
    )),
    target_type text NOT NULL CHECK (target_type IN ('usuario','juego','solicitud_creador','apelacion')),
    target_id text NOT NULL,
    target_label text,
    reason text,
    before_data jsonb NOT NULL DEFAULT '{}'::jsonb,
    after_data jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_audit_log_created_at_idx ON public.admin_audit_log (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS admin_audit_log_target_idx ON public.admin_audit_log (target_type, target_id, created_at DESC);
CREATE INDEX IF NOT EXISTS admin_audit_log_action_idx ON public.admin_audit_log (action_key, created_at DESC);
ALTER TABLE public.admin_audit_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.admin_audit_log FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.admin_audit_log TO authenticated;
GRANT ALL ON TABLE public.admin_audit_log TO service_role;
DROP POLICY IF EXISTS "admin_audit_log: solo staff lee" ON public.admin_audit_log;
CREATE POLICY "admin_audit_log: solo staff lee" ON public.admin_audit_log FOR SELECT TO authenticated USING ((SELECT private.mi_rol()) IN ('moderador','root'));
COMMENT ON TABLE public.admin_audit_log IS 'Registro de solo lectura para el personal administrativo. Las filas se escriben mediante triggers de auditoría.';

DROP POLICY IF EXISTS "usuarios: propio perfil o admin actualiza" ON public.usuarios;
CREATE POLICY "usuarios: propio perfil o admin actualiza" ON public.usuarios FOR UPDATE TO authenticated
USING (
  id = (SELECT auth.uid()) OR (
    id <> (SELECT auth.uid()) AND role <> 'root'
    AND (SELECT private.mi_rol()) IN ('moderador','root')
    AND ((SELECT private.mi_rol()) = 'root' OR role <> 'moderador')
  )
)
WITH CHECK (
  (id = (SELECT auth.uid()) AND role = (SELECT private.mi_rol()))
  OR (id <> (SELECT auth.uid()) AND role <> 'root' AND (
    (SELECT private.mi_rol()) = 'root'
    OR ((SELECT private.mi_rol()) = 'moderador' AND role NOT IN ('moderador','root'))
  ))
);

CREATE OR REPLACE FUNCTION public.admin_change_user_role(p_user_id uuid, p_new_role text, p_reason text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $function$
DECLARE
  v_actor_id uuid := auth.uid(); v_actor_role text := private.mi_rol(); v_old_role text; v_username text;
BEGIN
  IF v_actor_id IS NULL THEN RAISE EXCEPTION 'Tenés que iniciar sesión.'; END IF;
  IF v_actor_role NOT IN ('moderador','root') THEN RAISE EXCEPTION 'No tenés permisos para administrar usuarios.'; END IF;
  IF p_user_id IS NULL OR p_user_id = v_actor_id THEN RAISE EXCEPTION 'No podés modificar tu propio rol.'; END IF;
  IF p_new_role NOT IN ('usuario','creador','moderador','banned') THEN RAISE EXCEPTION 'El rol solicitado no está permitido. El rol root se reserva para configuración segura.'; END IF;
  IF v_actor_role = 'moderador' AND p_new_role = 'moderador' THEN RAISE EXCEPTION 'Solo root puede asignar el rol de moderador.'; END IF;
  IF p_new_role = 'banned' AND length(trim(coalesce(p_reason,''))) < 10 THEN RAISE EXCEPTION 'Para suspender una cuenta, indicá un motivo de al menos 10 caracteres.'; END IF;
  SELECT u.role, u.username INTO v_old_role, v_username FROM public.usuarios u WHERE u.id = p_user_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'No se encontró el usuario.'; END IF;
  IF v_old_role = 'root' THEN RAISE EXCEPTION 'La cuenta root está protegida y no puede modificarse desde el panel.'; END IF;
  IF v_old_role = 'moderador' AND v_actor_role <> 'root' THEN RAISE EXCEPTION 'Solo root puede modificar cuentas moderadoras.'; END IF;
  IF v_old_role = p_new_role THEN RETURN jsonb_build_object('ok', true, 'changed', false, 'role', v_old_role, 'username', v_username); END IF;
  PERFORM set_config('app.admin_action_reason', left(trim(coalesce(p_reason,'')),500), true);
  UPDATE public.usuarios u SET role = p_new_role WHERE u.id = p_user_id RETURNING u.role INTO v_old_role;
  IF NOT FOUND THEN RAISE EXCEPTION 'No se pudo actualizar el rol. Revisá los permisos.'; END IF;
  RETURN jsonb_build_object('ok', true, 'changed', true, 'role', v_old_role, 'username', v_username);
END;
$function$;
REVOKE ALL ON FUNCTION public.admin_change_user_role(uuid,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_change_user_role(uuid,text,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_resolver_juego(p_juego_id bigint, p_estado text, p_motivo text)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $function$
DECLARE
  v_actor_role text := private.mi_rol(); v_title text; v_old_status text; v_reason text := left(trim(coalesce(p_motivo,'')),1000);
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Tenés que iniciar sesión.'; END IF;
  IF v_actor_role NOT IN ('moderador','root') THEN RAISE EXCEPTION 'No tenés permisos para moderar publicaciones.'; END IF;
  IF p_estado NOT IN ('pendiente','aprobado','rechazado') THEN RAISE EXCEPTION 'Estado de moderación no válido.'; END IF;
  IF p_estado = 'rechazado' AND length(v_reason) < 10 THEN RAISE EXCEPTION 'Para rechazar una publicación, escribí un motivo de al menos 10 caracteres.'; END IF;
  SELECT j.title, j.estado_moderacion INTO v_title, v_old_status FROM public.juegos j WHERE j.id = p_juego_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'No se encontró la publicación.'; END IF;
  IF v_old_status = p_estado THEN RAISE EXCEPTION 'La publicación ya tiene ese estado.'; END IF;
  PERFORM set_config('app.admin_action_reason', v_reason, true);
  UPDATE public.juegos j SET estado_moderacion = p_estado, motivo_revision = CASE WHEN p_estado = 'rechazado' THEN v_reason ELSE NULL END WHERE j.id = p_juego_id;
  RETURN jsonb_build_object('ok', true, 'id', p_juego_id, 'title', v_title, 'estado', p_estado);
END;
$function$;
REVOKE ALL ON FUNCTION public.admin_resolver_juego(bigint,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_resolver_juego(bigint,text,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.registrar_auditoria_admin()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $function$
DECLARE
  v_actor_id uuid := auth.uid(); v_actor_role text; v_actor_username text; v_action text; v_target_type text;
  v_target_id text; v_target_label text; v_reason text; v_before jsonb := '{}'::jsonb; v_after jsonb := '{}'::jsonb;
BEGIN
  v_actor_role := coalesce(private.mi_rol(), nullif(current_setting('request.jwt.claim.role', true), ''), 'system');
  IF v_actor_id IS NOT NULL THEN SELECT u.username INTO v_actor_username FROM public.usuarios u WHERE u.id = v_actor_id; END IF;
  IF TG_TABLE_NAME = 'usuarios' THEN
    IF OLD.role IS NOT DISTINCT FROM NEW.role THEN RETURN NEW; END IF;
    v_action := 'user.role_changed'; v_target_type := 'usuario'; v_target_id := NEW.id::text; v_target_label := NEW.username;
    v_before := jsonb_build_object('role', OLD.role); v_after := jsonb_build_object('role', NEW.role);
    v_reason := nullif(current_setting('app.admin_action_reason', true), '');
  ELSIF TG_TABLE_NAME = 'juegos' AND TG_OP = 'DELETE' THEN
    v_action := 'game.deleted'; v_target_type := 'juego'; v_target_id := OLD.id::text; v_target_label := OLD.title;
    v_before := jsonb_build_object('title', OLD.title, 'estado_moderacion', OLD.estado_moderacion, 'user_id', OLD.user_id);
  ELSIF TG_TABLE_NAME = 'juegos' THEN
    IF OLD.estado_moderacion IS NOT DISTINCT FROM NEW.estado_moderacion THEN RETURN NEW; END IF;
    v_action := 'game.moderation_changed'; v_target_type := 'juego'; v_target_id := NEW.id::text; v_target_label := NEW.title;
    v_before := jsonb_build_object('estado_moderacion', OLD.estado_moderacion);
    v_after := jsonb_build_object('estado_moderacion', NEW.estado_moderacion, 'revisado_por', NEW.revisado_por, 'revisado_at', NEW.revisado_at);
    v_reason := nullif(NEW.motivo_revision, '');
  ELSIF TG_TABLE_NAME = 'solicitudes_creador' THEN
    IF OLD.estado IS NOT DISTINCT FROM NEW.estado THEN RETURN NEW; END IF;
    v_action := 'creator_request.resolved'; v_target_type := 'solicitud_creador'; v_target_id := NEW.id::text;
    SELECT u.username INTO v_target_label FROM public.usuarios u WHERE u.id = NEW.user_id;
    v_before := jsonb_build_object('estado', OLD.estado);
    v_after := jsonb_build_object('estado', NEW.estado, 'user_id', NEW.user_id, 'revisado_por', NEW.revisado_por, 'revisado_at', NEW.revisado_at);
  ELSIF TG_TABLE_NAME = 'apelaciones' THEN
    IF OLD.estado IS NOT DISTINCT FROM NEW.estado THEN RETURN NEW; END IF;
    v_action := 'appeal.resolved'; v_target_type := 'apelacion'; v_target_id := NEW.id::text;
    SELECT u.username INTO v_target_label FROM public.usuarios u WHERE u.id = NEW.user_id;
    v_before := jsonb_build_object('estado', OLD.estado);
    v_after := jsonb_build_object('estado', NEW.estado, 'user_id', NEW.user_id, 'revisado_por', NEW.revisado_por, 'revisado_at', NEW.revisado_at);
  ELSE RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;
  INSERT INTO public.admin_audit_log(actor_id,actor_username,actor_role,action_key,target_type,target_id,target_label,reason,before_data,after_data)
  VALUES(v_actor_id,v_actor_username,v_actor_role,v_action,v_target_type,v_target_id,v_target_label,v_reason,coalesce(v_before,'{}'::jsonb),coalesce(v_after,'{}'::jsonb));
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$function$;
REVOKE ALL ON FUNCTION public.registrar_auditoria_admin() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS audit_usuario_role_change ON public.usuarios;
CREATE TRIGGER audit_usuario_role_change AFTER UPDATE OF role ON public.usuarios FOR EACH ROW WHEN (OLD.role IS DISTINCT FROM NEW.role) EXECUTE FUNCTION public.registrar_auditoria_admin();
DROP TRIGGER IF EXISTS audit_game_moderation_change ON public.juegos;
CREATE TRIGGER audit_game_moderation_change AFTER UPDATE OF estado_moderacion ON public.juegos FOR EACH ROW WHEN (OLD.estado_moderacion IS DISTINCT FROM NEW.estado_moderacion) EXECUTE FUNCTION public.registrar_auditoria_admin();
DROP TRIGGER IF EXISTS audit_game_delete ON public.juegos;
CREATE TRIGGER audit_game_delete AFTER DELETE ON public.juegos FOR EACH ROW EXECUTE FUNCTION public.registrar_auditoria_admin();
DROP TRIGGER IF EXISTS audit_creator_request_resolution ON public.solicitudes_creador;
CREATE TRIGGER audit_creator_request_resolution AFTER UPDATE OF estado ON public.solicitudes_creador FOR EACH ROW WHEN (OLD.estado IS DISTINCT FROM NEW.estado) EXECUTE FUNCTION public.registrar_auditoria_admin();
DROP TRIGGER IF EXISTS audit_appeal_resolution ON public.apelaciones;
CREATE TRIGGER audit_appeal_resolution AFTER UPDATE OF estado ON public.apelaciones FOR EACH ROW WHEN (OLD.estado IS DISTINCT FROM NEW.estado) EXECUTE FUNCTION public.registrar_auditoria_admin();

